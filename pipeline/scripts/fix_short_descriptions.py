def extract_instruction_steps(desc: str) -> str:
    """Извлекает <ol>...</ol> или <ul>...</ul> блок из существующего описания."""
    # Ищем секцию <h2>Инструкция...
    m = re.search(r'<h2>Инструкция[^<]*</h2>(.*?)(?=<h2>|$)', desc, re.DOTALL)
    if m:
        return m.group(1).strip()
    # Ищем любой ol/ul блок
    m = re.search(r'(<(?:ol|ul)>.*?</(?:ol|ul)>)', desc, re.DOTALL)
    if m:
        return m.group(1).strip()
    return ""


