def build_h2(title: str, country: str) -> str:
    """Строит h2 из первой части заголовка."""
    first_part = title.split("|")[0].strip()
    country_clean = country.strip()
    return f"<h2>{first_part} — {country_clean}</h2>"


def build_description(row: list) -> str:
    sku = row[0]
    title = str(row[6] or "")
    desc = str(row[9] or "")
    применение = str(row[39] or "")
    назначение = str(row[40] or "")
    сервис = str(row[41] or "")
    страна = str(row[48] or "")

    content = get_service_content(сервис, применение, назначение, title)
    steps_block = extract_instruction_steps(desc)

    h2 = build_h2(title, страна)
    intro_p = f"<p>{content['intro']}</p>"

    benefits_header = f"<p><b>{content['benefits_header']}</b></p>"
    benefits_li = "\n".join(f"<li>{b}</li>" for b in content["benefits"])
    benefits_block = f"<ul>\n{benefits_li}\n</ul>"

    if steps_block:
        how_section = f"<h2>Как активировать</h2>\n{steps_block}"
    else:
        how_section = ""

    notice_li = "\n".join(f"<li>{n}</li>" for n in content["notice"])
    notice_block = f"<p><b>Обратите внимание:</b></p>\n<ul>\n{notice_li}\n</ul>"

    parts = [h2, intro_p, benefits_header, benefits_block]
    if how_section:
        parts.append(how_section)
    parts.append(notice_block)

    return "\n".join(parts)


